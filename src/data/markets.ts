function genHistory(start: number, length = 60): { date: string; price: number }[] {
  const points = []
  let price = start + (Math.random() - 0.5) * 20
  const now = Date.now()
  for (let i = length; i >= 0; i--) {
    price = Math.max(2, Math.min(98, price + (Math.random() - 0.48) * 4))
    const d = new Date(now - i * 24 * 60 * 60 * 1000)
    points.push({ date: d.toISOString().slice(0, 10), price: Math.round(price) })
  }
  return points
}

